export interface HelperEntry {
  path: string;
  name: string;
}

/** Finds named exports that are declarations, including multiline function signatures. */
export function exportedNames(source: string): string[] {
  const names = new Set<string>();
  const declaration = /\bexport\s+(?:declare\s+)?(?:async\s+)?(?:function|class|const|let|var|interface|type|enum)\s+([A-Za-z_$][\w$]*)/g;
  for (const match of source.matchAll(declaration)) names.add(match[1]!);
  const reexports = /\bexport\s*\{([\s\S]*?)\}/g;
  for (const match of source.matchAll(reexports)) {
    const block = match[1]!.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "");
    for (const item of block.split(",")) {
      const parts = item.trim().replace(/^type\s+/, "").split(/\s+as\s+/);
      const name = parts.at(-1)?.trim();
      if (name && /^[A-Za-z_$][\w$]*$/.test(name)) names.add(name);
    }
  }
  return [...names].sort((a, b) => a.localeCompare(b));
}

/** Stable per-home page, one line per exported helper. */
export function renderHelperPage(title: string, entries: readonly HelperEntry[]): string {
  const sorted = [...entries].sort((a, b) => a.name.localeCompare(b.name) || a.path.localeCompare(b.path));
  const lines = [
    `# ${title} helpers`,
    "",
    "Generated by `bun run helpers` from exported declarations in shared helper homes.",
    "",
    `${sorted.length} exports.`,
    "",
  ];
  for (const entry of sorted) lines.push(`- \`${entry.name}\`: \`${entry.path}\``);
  return `${lines.join("\n")}\n`;
}

/** Small root index; details are split by actual source home to stay within the file cap. */
export function renderHelpersIndex(groups: ReadonlyMap<string, readonly HelperEntry[]>): string {
  const lines = [
    "# Helpers index",
    "",
    "Generated by `bun run helpers` from exported declarations in shared helper homes.",
    "Before adding a helper, find its existing home here and extend that module when it fits.",
    "",
  ];
  for (const [area, entries] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`- ${area}: ${entries.length} exports in [the helper index](docs/generated/helpers/${area}.md)`);
  }
  return `${lines.join("\n")}\n`;
}
