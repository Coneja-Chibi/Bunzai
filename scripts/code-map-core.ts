/**
 * The code map's pure half: which files it covers, each file's purpose (the first sentence of its
 * opening documentation block, which scan:headers already requires), and the page itself. No
 * filesystem or git here, so the rules are unit-tested (code-map-core.test.ts) and the shell
 * (code-map.ts) can read either the working tree or git's staged snapshot.
 */

import { SKIP_DIRS } from "./hooks/file-selection";

/** Folders the map starts from. Tests are left out: their purpose is the file they test. */
export const MAP_ROOTS = ["src", "scripts"] as const;
/** Longest purpose kept on one line of the map, so the page stays scannable. */
const MAX_PURPOSE = 220;

/** True when a repo path belongs on the map: authored TS or TSX under a map root, not a test. */
export function onMap(rawPath: string): boolean {
  const path = rawPath.replace(/\\/g, "/");
  if (!MAP_ROOTS.some((root) => path.startsWith(`${root}/`))) return false;
  if (!/\.tsx?$/.test(path) || /\.d\.ts$/.test(path) || /\.test\.tsx?$/.test(path)) return false;
  const dirs = path.split("/").slice(0, -1);
  return !dirs.some((d) => SKIP_DIRS.has(d) || d.startsWith("."));
}

/**
 * The first sentence of a file's opening documentation block, as one line. A block with no
 * sentence end is used whole, then cut to length. Null when the file has no opening block.
 */
export function purposeOf(source: string): string | null {
  let text = source.replace(/^﻿/, "");
  if (text.startsWith("#!")) text = text.slice(text.indexOf("\n") + 1);
  // A tag-only block first (`/** @jsxImportSource ... */`) is a compiler setting, not the purpose:
  // skip it and read the block after it.
  let prose = "";
  while (text.startsWith("/**")) {
    const end = text.indexOf("*/");
    if (end < 0) return null;
    prose = text
      .slice(3, end)
      .split("\n")
      .map((line) => line.replace(/^\s*\*\s?/, "").trim())
      .filter((line) => !line.startsWith("@"))
      .join(" ")
      .replace(/\s+/g, " ")
      .trim();
    if (prose) break;
    text = text.slice(end + 2).trimStart();
  }
  if (!prose) return null;
  // A sentence ends at ". " or at the end; "e.g. " and "src/x.ts " never end one.
  const match = /^(.+?[.!?])(\s|$)/.exec(prose.replace(/\b(e\.g|i\.e|etc|vs)\./g, "$1\u0000"));
  let sentence = (match ? match[1]! : prose).replace(/\u0000/g, ".");
  if (sentence.length > MAX_PURPOSE) sentence = `${sentence.slice(0, MAX_PURPOSE - 3).trimEnd()}...`;
  return sentence;
}

export interface MapEntry {
  path: string;
  purpose: string | null;
}

/** The page: one section per folder, one line per file, in path order, with no dates (stable output). */
export function renderCodeMap(entries: readonly MapEntry[]): string {
  const byDir = new Map<string, MapEntry[]>();
  for (const e of [...entries].sort((a, b) => a.path.localeCompare(b.path))) {
    const dir = e.path.slice(0, e.path.lastIndexOf("/"));
    byDir.set(dir, [...(byDir.get(dir) ?? []), e]);
  }
  const lines = [
    "# Code map",
    "",
    "Generated by `bun run codemap` from the first sentence of each source file's opening comment.",
    "Do not edit by hand: change the file's comment and regenerate (the commit hook does it for you).",
    "Tests are left out. For what a project word means, see [the glossary](../reference/glossary.md).",
    "",
    `${entries.length} files.`,
  ];
  for (const [dir, files] of byDir) {
    lines.push("", `## ${dir}/`, "");
    for (const f of files) lines.push(`- \`${f.path.slice(dir.length + 1)}\`: ${f.purpose ?? "(no opening comment)"}`);
  }
  return `${lines.join("\n")}\n`;
}
