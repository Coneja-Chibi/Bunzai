/** The theme parts page's pure rules: read every `data-part` name out of a component source, and render the author-facing table. */

export interface PartHit {
  part: string;
  tag: string;
  file: string;
}

/** A literal name, a choice between two literals, or a template whose `${...}` pieces (an id the code keys on) are written `<id>` in the page. */
const ATTRIBUTE = /data-part=(?:"([^"]*)"|\{`([^`]*)`\}|\{[^"'`{}?]+\?\s*"([^"]*)"\s*:\s*"([^"]*)"\})/g;
const NAME = /^[a-z][a-z0-9-]*(?:\.[a-z][a-z0-9-]*)+(?:\.<id>)*$/;

/** Each stable part name in one source file, with the element it sits on (the nearest opening tag before it). */
export function partsIn(source: string, file: string): PartHit[] {
  const hits: PartHit[] = [];
  for (const match of source.matchAll(ATTRIBUTE)) {
    const names = match[3] === undefined ? [match[1] ?? match[2]!.replace(/\$\{[^}]*\}/g, "<id>")] : [match[3], match[4]!];
    const before = source.slice(0, match.index);
    const tag = /<([A-Za-z][\w.]*)(?![\s\S]*<[A-Za-z])[\s\S]*$/.exec(before)?.[1] ?? "?";
    for (const part of names) if (NAME.test(part)) hits.push({ part, tag, file });
  }
  return hits;
}

/** One row per part name, sorted; where one name sits on several elements or files, all are listed. */
export function renderParts(hits: readonly PartHit[]): string {
  const byPart = new Map<string, { tags: Set<string>; files: Set<string> }>();
  for (const hit of hits) {
    const row = byPart.get(hit.part) ?? { tags: new Set<string>(), files: new Set<string>() };
    row.tags.add(hit.tag);
    row.files.add(hit.file);
    byPart.set(hit.part, row);
  }
  const surfaces = new Map<string, string[]>();
  for (const part of [...byPart.keys()].sort()) {
    const surface = part.split(".")[0]!;
    const row = byPart.get(part)!;
    const line = `| \`${part}\` | ${[...row.tags].sort().map((t) => `\`${t}\``).join(", ")} | ${[...row.files].sort().map((f) => `\`${f}\``).join(", ")} |`;
    surfaces.set(surface, [...(surfaces.get(surface) ?? []), line]);
  }
  const sections = [...surfaces].map(([surface, lines]) => `### ${surface}\n\n| Part | Element | Source |\n| --- | --- | --- |\n${lines.join("\n")}`);
  return `<!-- GENERATED by scripts/docs-parts.ts from the data-part attributes in src/ui - do not edit by hand -->\n\n${sections.join("\n\n")}\n`;
}

/** The check's verdict: null when the committed page matches a fresh render, else the reason it fails. */
export function staleReason(committed: string | null, hits: readonly PartHit[]): string | null {
  if (committed === null) return "the theme parts page is missing";
  return committed === renderParts(hits) ? null : "the theme parts page is stale";
}
