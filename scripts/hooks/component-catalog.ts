/**
 * The component catalog's imperative shell: walks the UI tree, runs catalog-lib's pure extraction
 * over every file, and turns the result into docs/reference/components.md. Covers BOTH renderer
 * UI entries: React components anywhere under src/ui (.tsx), plus exported
 * create/build/swatch/inject helpers in src/ui/_shared (.ts). A drop-in folder gains no
 * special treatment here - the glob patterns are the one seam,
 * matching the repo's folders-as-schema doctrine.
 *
 * Modes:
 *   (default)  write docs/reference/components.md
 *   --check    exit 2 if the on-disk file would differ from a fresh generation (pre-commit gate)
 *   --digest   print a compact one-line-per-entry listing to stdout (SessionStart context injection)
 *
 * Run: bun run scripts/hooks/component-catalog.ts [--check|--digest]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { cssClassNames, extractCatalogEntries, type CatalogEntry } from "./catalog-lib";

// ONE glob over all of src/ui (folders-as-schema): the old four-dir hand-list silently omitted
// src/ui/setup, so exported components there never reached the catalog while --check passed.
const GLOBS = ["src/ui/**/*.{tsx,ts}"];

const OUT_PATH = "docs/reference/components.md";

/** Every file the catalog scans, deduped and sorted for a deterministic scan order. */
function collectFiles(): string[] {
  const files = new Set<string>();
  for (const pattern of GLOBS) {
    for (const f of new Bun.Glob(pattern).scanSync({ cwd: process.cwd() })) {
      const p = f.replace(/\\/g, "/");
      if (/\.test\.tsx?$/.test(p)) continue;
      files.add(p);
    }
  }
  return [...files].sort();
}

/** Classes from imported stylesheets; sibling fallback remains for components without CSS imports. */
function stylesFor(file: string, source: string): string[] | undefined {
  const cssImports = [...source.matchAll(/\bimport\s+(?:(?:[^'";]+?)\s+from\s+)?["']([^"']+\.css)["']/g)]
    .map((match) => match[1]!);
  const imported = cssImports.filter((specifier) => specifier.startsWith("."));
  if (cssImports.length > 0) {
    const names = new Set<string>();
    for (const specifier of imported) {
      const path = join(dirname(file), specifier);
      if (!existsSync(path)) continue;
      for (const name of cssClassNames(readFileSync(path, "utf8"))) names.add(name);
    }
    return [...names];
  }
  const candidates = ["styles.module.css", "Editor.module.css"];
  for (const name of candidates) {
    const p = join(dirname(file), name);
    if (existsSync(p)) return cssClassNames(readFileSync(p, "utf8"));
  }
  return undefined;
}

function allEntries(files: string[]): CatalogEntry[] {
  const entries: CatalogEntry[] = [];
  for (const file of files) {
    const source = readFileSync(file, "utf8");
    for (const entry of extractCatalogEntries(file, source)) {
      entries.push(entry.kind === "component" ? { ...entry, styles: stylesFor(file, source) } : entry);
    }
  }
  // kind then name (both alphabetical): "component" sorts before "shared-helper" on its own, so this
  // one comparator gives the grouped, deterministic order the table renders in.
  return entries.sort((a, b) => (a.kind === b.kind ? a.name.localeCompare(b.name) : a.kind.localeCompare(b.kind)));
}

const escapeCell = (s: string): string => s.replace(/\|/g, "\\|");

function table(rows: CatalogEntry[], emptyNote: string): string {
  if (rows.length === 0) return `_${emptyNote}_\n`;
  const body = rows
    .map(
      (e) =>
        `| ${escapeCell(e.name)} | ${escapeCell(e.file)} | ${escapeCell(e.signature)} | ${escapeCell(e.doc)} | ${escapeCell(
          e.styles?.length ? `.${e.styles.slice(0, 8).join(" .")}${e.styles.length > 8 ? " ..." : ""}` : "",
        )} |`,
    )
    .join("\n");
  return `| Name | File | Signature | Doc | Styles |\n| --- | --- | --- | --- | --- |\n${body}\n`;
}

function renderMarkdown(entries: CatalogEntry[]): string {
  const components = entries.filter((e) => e.kind === "component");
  const helpers = entries.filter((e) => e.kind === "shared-helper");
  return `# Component catalog

Auto-generated by \`scripts/hooks/component-catalog.ts\` from exported UI entries under
\`src/ui\` (\`.tsx\` React components, ADR-008) and exported create/build/swatch/inject helpers in
\`src/ui/_shared\` (\`.ts\`). Do not hand-edit: regenerate with
\`bun run scripts/hooks/component-catalog.ts\`. A
pre-commit gate (\`--check\`) fails the commit when this file drifts from the real exports.

## Use this for

The answer for the common needs, before searching the table below. For buttons, color pickers and fonts, lint and the style guard block the alternatives.

| Need | Use |
| --- | --- |
| Any action with text | \`Button\` (src/ui/components/button): primary once per view, danger for destructive, quiet for low emphasis |
| An icon-only action | \`IconButton\` with a \`label\` |
| One (or several) of a few options | \`Segmented\` |
| Sections of a room or editor | \`Tabs\` |
| A small on/off filter or tag | \`Chip\` |
| A row in a list, rail or picker | \`ListRow\` |
| A row in a popup menu | \`MenuItem\` |
| A header that opens and closes a section | \`Disclosure\` |
| A small square (rail icon, swatch, thumb, app, add) | \`Tile\` |
| A larger clickable surface (choice, art, entry, file drop) | \`Card\` |
| A pager dot, canvas port or handle | \`Dot\` |
| A value inside text that edits on click | \`InlineValue\` |
| The click-away layer behind a wing or menu | \`Scrim\` |
| A document tab | \`DocTab\` |
| An icon | \`Ic\` (src/ui/_shared/ic.tsx) |
| A color | \`SwatchRow\`; solid or gradient fill: \`PaintPicker\` |
| An on/off switch | \`Toggle\` (\`card\` for a whole-row setting card) |
| A dialog | \`InkDialog\` or \`DialogCore\` |
| Fonts | \`var(--font-fancy)\` titles, \`var(--font-body)\` text, \`var(--font-mono)\` code; never a font name |

## Components (React, \`.tsx\`)

${table(components, "None yet - the .tsx conversion (ADR-008) has not landed a component here")}
## Shared UI helpers (\`src/ui/_shared\`, \`.ts\`)

${table(helpers, "None found")}`;
}

function main(): number {
  const entries = allEntries(collectFiles());

  if (process.argv.includes("--digest")) {
    for (const e of entries) console.log(`${e.kind}\t${e.name}\t${e.file}\t${e.signature}`);
    return 0;
  }

  const content = renderMarkdown(entries);

  if (process.argv.includes("--check")) {
    const onDisk = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : "";
    if (onDisk !== content) {
      console.error(`component-catalog: ${OUT_PATH} is stale. Run: bun run scripts/hooks/component-catalog.ts`);
      return 2;
    }
    return 0;
  }

  writeFileSync(OUT_PATH, content);
  return 0;
}

process.exit(main());
